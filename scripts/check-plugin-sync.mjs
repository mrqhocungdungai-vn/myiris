#!/usr/bin/env node
// Checks the vendored Claude Code configuration two ways:
//
//   1. DUPLICATION — every file present in BOTH `.claude/` and the plugin tree
//      that ships inside the packaged app must be identical, unless an allowance
//      says why it differs. Two copies of one workflow with nothing keeping them
//      together is the failure CLAUDE.md already names about verbs: "A verb is
//      defined in exactly one place… three hand-wired copies is the mechanism that
//      produced the silently-dropped appendSystemPrompt." The principle had never
//      been applied to the configuration surface, and the surface had already
//      started drifting when this check was written — twelve pairs of it.
//
//   2. PROVENANCE — every file recorded in skills-lock.json must still hash to its
//      recorded `installedHash`. See that file's `_readme`: v1's `computedHash` was
//      the hash of the UPSTREAM source, matched no installed file, and nothing
//      noticed for years because nothing read it.
//
// This check REPORTS and never writes. `resources/iris-plugin/` is shipped via
// package.json's `extraResources` and loaded by the packaged app, so reconciling a
// divergence changes what the app runs — a decision to take deliberately, not a
// side effect of a check running.
//
// It is NOT a sixth gate. It is attached to `npm run build` alongside
// check-three-dedupe.mjs and check-types-node.mjs, which are also build-attached
// and also not counted among the five. CLAUDE.md, docs/TESTING.md and the
// workflow-quality-gates spec all say five; a hash comparison does not get to
// change that.
//
// See openspec/specs/claude-code-config/spec.md.
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

export const REPO_ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");

const TAG = "[plugin-sync]";

/** The subdirectories the two trees are expected to hold the same files in. */
const SHARED_SUBDIRS = ["skills", "commands"];

// ---------------------------------------------------------------------------
// Allowances (same shape as check-spec-drift.mjs's): keyed to one specific pair,
// each carrying its own stated reason. Never a directory-wide exemption — a
// blanket pass for `openspec-*` would silently cover a content divergence
// introduced later for an entirely different reason.
// ---------------------------------------------------------------------------

const OPENSPEC_VERSION_SKEW =
  "Generated by the OpenSpec CLI, and the two trees were generated by different versions " +
  "(`generatedBy: 1.7.0` in .claude/, 1.6.0 in the plugin). Regenerating the plugin copy " +
  "changes what ships inside the packaged app, so it is deliberately a separate change " +
  "(claude-config-earns-its-place D6).";

export const ALLOWANCES = [
  ...[
    "openspec-apply-change",
    "openspec-archive-change",
    "openspec-explore",
    "openspec-propose",
    "openspec-sync-specs",
    "openspec-update-change",
  ].map((name) => ({ file: `skills/${name}/SKILL.md`, reason: OPENSPEC_VERSION_SKEW })),
  ...["apply", "archive", "explore", "propose", "sync", "update"].map((name) => ({
    file: `commands/opsx/${name}.md`,
    reason:
      `${OPENSPEC_VERSION_SKEW} Additionally, the .claude/ copy carries an \`argument-hint\`, ` +
      "added locally in the same change. That field is an affordance for the developer's " +
      "slash-command picker and means nothing to the worker that loads the plugin, so it is " +
      "deliberately NOT mirrored into the shipped tree.",
  })),
];

// ---------------------------------------------------------------------------

function sha256(absolute) {
  return createHash("sha256").update(fs.readFileSync(absolute)).digest("hex");
}

/** Every file under `root`, as paths relative to it. Missing root yields nothing. */
function filesUnder(root) {
  if (!fs.existsSync(root)) return [];
  return fs
    .readdirSync(root, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => path.relative(root, path.join(entry.parentPath ?? entry.path, entry.name)));
}

/**
 * Compare the files the two trees have in common.
 *
 * Only the intersection is checked. A file present in one tree and not the other
 * is not a divergence: the plugin ships wiki skills the developer surface has no
 * use for, and `.claude/` holds agents the app never loads. Requiring the two to
 * hold the same SET of files would be a different and wrong requirement.
 */
function checkDuplication({ claudeDir, pluginDir, allowanceFor }) {
  const problems = [];
  let compared = 0;
  let allowed = 0;

  for (const subdir of SHARED_SUBDIRS) {
    const claudeSub = path.join(claudeDir, subdir);
    const pluginSub = path.join(pluginDir, subdir);
    const pluginFiles = new Set(filesUnder(pluginSub));

    for (const relative of filesUnder(claudeSub)) {
      if (!pluginFiles.has(relative)) continue;
      const key = `${subdir}/${relative}`;
      compared += 1;

      if (sha256(path.join(claudeSub, relative)) === sha256(path.join(pluginSub, relative))) {
        if (allowanceFor(key)) {
          problems.push(
            `${TAG} STALE ALLOWANCE: ${key} now matches, so its allowance is obsolete — remove it.`,
          );
        }
        continue;
      }

      const allowance = allowanceFor(key);
      if (allowance) {
        allowed += 1;
        continue;
      }
      problems.push(
        `${TAG} DIVERGED: ${key}`,
        `${TAG}   .claude/${key}`,
        `${TAG}   resources/iris-plugin/${key}`,
        `${TAG}   These are two SEPARATE surfaces that happen to hold a copy of the same file:`,
        `${TAG}   .claude/ configures the developer's editing loop; resources/iris-plugin/ is`,
        `${TAG}   bundled into the app and is the only source the shipped worker reads. This`,
        `${TAG}   check reports divergence — it does NOT mean they should be made identical.`,
        `${TAG}   Either change one side deliberately (editing the plugin changes what the app`,
        `${TAG}   does), or add an allowance here stating why they differ.`,
      );
    }
  }

  return { problems, summary: `${compared} shared file(s), ${allowed} declared divergence(s)` };
}

/**
 * Verify every locked file still hashes to its recorded `installedHash`.
 *
 * A missing recorded file fails too: the lock is a claim about what is present, so
 * an entry with no file is the record describing a repo that no longer exists.
 */
function checkProvenance({ repoRoot, claudeDir }) {
  const problems = [];
  const lockPath = path.join(repoRoot, "skills-lock.json");
  if (!fs.existsSync(lockPath)) {
    return { problems: [`${TAG} skills-lock.json is missing — vendored config has no provenance.`], summary: "" };
  }

  let lock;
  try {
    lock = JSON.parse(fs.readFileSync(lockPath, "utf8"));
  } catch (error) {
    return { problems: [`${TAG} skills-lock.json is not valid JSON: ${error.message}`], summary: "" };
  }

  const targets = [
    ...Object.entries(lock.skills ?? {}).map(([name, entry]) => ({
      label: `skills/${name}/SKILL.md`,
      absolute: path.join(claudeDir, "skills", name, "SKILL.md"),
      entry,
    })),
    ...Object.entries(lock.agents ?? {}).map(([name, entry]) => ({
      label: `agents/${name}.md`,
      absolute: path.join(claudeDir, "agents", `${name}.md`),
      entry,
    })),
  ];

  for (const { label, absolute, entry } of targets) {
    if (!entry.installedHash) {
      problems.push(`${TAG} ${label} is locked but records no installedHash — nothing to verify against.`);
      continue;
    }
    if (!fs.existsSync(absolute)) {
      problems.push(
        `${TAG} MISSING: ${label} is recorded in skills-lock.json but is not installed.`,
        `${TAG}   Either reinstall it, or drop its entry so the lock describes what is present.`,
      );
      continue;
    }
    const actual = sha256(absolute);
    if (actual !== entry.installedHash) {
      problems.push(
        `${TAG} CHANGED: ${label} no longer matches its recorded installedHash.`,
        `${TAG}   recorded ${entry.installedHash}`,
        `${TAG}   actual   ${actual}`,
        `${TAG}   If the edit was intended, update installedHash in skills-lock.json.`,
      );
    }
  }

  return { problems, summary: `${targets.length} locked file(s)` };
}

/**
 * Composes like the other checks: returns a verdict, never calls process.exit.
 *
 * Dependencies are injected with production defaults, per the repo's testability
 * convention — so the tests exercise the check's logic against synthetic trees
 * rather than asserting today's state of the real one.
 */
export function checkPluginSync({
  repoRoot = REPO_ROOT,
  claudeDir = path.join(repoRoot, ".claude"),
  pluginDir = path.join(repoRoot, "resources", "iris-plugin"),
  allowances = ALLOWANCES,
} = {}) {
  const allowanceFor = (relative) => allowances.find((allowance) => allowance.file === relative);
  const duplication = checkDuplication({ claudeDir, pluginDir, allowanceFor });
  const provenance = checkProvenance({ repoRoot, claudeDir });
  const problems = [...duplication.problems, ...provenance.problems];

  if (problems.length > 0) return { ok: false, output: problems.join("\n") };
  return {
    ok: true,
    output: `${TAG} OK — ${duplication.summary}; ${provenance.summary} verified.`,
  };
}
